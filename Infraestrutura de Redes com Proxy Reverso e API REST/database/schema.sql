-- Execute este script no PostgreSQL como um usuario administrador.
-- A senha de exemplo deve ser substituida por uma senha forte.

CREATE USER api_user WITH PASSWORD 'troque_esta_senha';
CREATE DATABASE clientes_db OWNER api_user;

\connect clientes_db

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    telefone VARCHAR(25),
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE clientes OWNER TO api_user;

