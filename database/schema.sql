-- Criação do usuário da aplicação, caso ainda não exista.
SELECT 'CREATE ROLE api_user LOGIN PASSWORD ''cliente123'''
    WHERE NOT EXISTS (
    SELECT 1 FROM pg_roles WHERE rolname = 'api_user'
)
    \gexec

-- Criação do banco, caso ainda não exista.
SELECT 'CREATE DATABASE clientes_db OWNER api_user'
    WHERE NOT EXISTS (
    SELECT 1 FROM pg_database WHERE datname = 'clientes_db'
)
    \gexec

-- Conexão ao banco da aplicação.
    \connect clientes_db

-- Garantir acesso ao schema.
    GRANT USAGE, CREATE ON SCHEMA public TO api_user;

-- Criar a tabela de clientes.
CREATE TABLE IF NOT EXISTS public.clientes (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    telefone VARCHAR(25),
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

-- Garantir que o usuário da API seja proprietário da tabela.
ALTER TABLE public.clientes OWNER TO api_user;

-- Permissões para a aplicação.
GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.clientes TO api_user;

GRANT USAGE, SELECT
             ON ALL SEQUENCES IN SCHEMA public TO api_user;

